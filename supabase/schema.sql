-- ── 4.1 get_my_role() — returns the current user's role from the users table ─

CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS user_role
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    RETURN (SELECT role FROM public.users WHERE id = auth.uid());
END;
$$;

REVOKE EXECUTE ON FUNCTION public.get_my_role() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_my_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_my_role() TO service_role;


-- ── 4.2 handle_new_user() — auto-populate users + extension table on signup ──

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_role user_role;
BEGIN
    v_role := COALESCE(new.raw_user_meta_data->>'role', 'student')::user_role;

    -- Insert into base users table
    INSERT INTO public.users (
        id, email, role, full_name, branch, phone, approval_status, created_at
    )
    VALUES (
        new.id,
        new.email,
        v_role,
        COALESCE(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
        COALESCE(new.raw_user_meta_data->>'branch', new.raw_user_meta_data->>'department'),
        new.raw_user_meta_data->>'phone',
        COALESCE(new.raw_user_meta_data->>'approval_status', 'approved'),
        NOW()
    )
    ON CONFLICT (id) DO UPDATE SET
        full_name       = EXCLUDED.full_name,
        branch          = EXCLUDED.branch,
        phone           = EXCLUDED.phone,
        approval_status = EXCLUDED.approval_status;

    -- Insert into role-specific extension table
    IF v_role = 'student' THEN
        INSERT INTO public.student_details (
            user_id, sbrn, semester, session
        ) VALUES (
            new.id,
            new.raw_user_meta_data->>'student_id',
            NULLIF(new.raw_user_meta_data->>'semester', '')::INTEGER,
            new.raw_user_meta_data->>'session'
        )
        ON CONFLICT (user_id) DO UPDATE SET
            sbrn     = EXCLUDED.sbrn,
            semester = EXCLUDED.semester,
            session  = EXCLUDED.session;

    ELSIF v_role = 'teacher' THEN
        INSERT INTO public.teacher_details (user_id)
        VALUES (new.id)
        ON CONFLICT DO NOTHING;

    ELSIF v_role = 'admin' THEN
        INSERT INTO public.admin_details (user_id)
        VALUES (new.id)
        ON CONFLICT DO NOTHING;
    END IF;

    RETURN new;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM PUBLIC;


-- ── 4.3 Auth Trigger ────────────────────────────────────────────────────────

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();


