COMMENT ON TABLE public.admin_details IS 'Role-specific extension for admins. Thin now — ready for multi-admin scoped permissions.';


-- ── 2.5 Courses ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.courses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key    TEXT UNIQUE,
    source        TEXT DEFAULT 'manual' CHECK (source IN ('manual', 'timetable')),
