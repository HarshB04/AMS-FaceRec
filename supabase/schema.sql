-- 6. DATA MIGRATION (idempotent — safe to re-run)
-- ════════════════════════════════════════════════════════════════════════════

-- Backfill users from existing profiles
INSERT INTO public.users (id, role, email, full_name, phone, avatar_url, branch, approval_status, created_at, updated_at)
SELECT
    p.id,
    p.role,
    p.email,
    COALESCE(p.full_name, split_part(p.email, '@', 1)),
    p.phone,
    p.profile_image,
    p.branch,
    COALESCE(p.approval_status, 'approved'),
    COALESCE(p.created_at, NOW()),
    NOW()
FROM public.profiles p
ON CONFLICT (id) DO UPDATE SET
    role      = EXCLUDED.role,
    email     = EXCLUDED.email,
    full_name = EXCLUDED.full_name,
    branch    = EXCLUDED.branch;

-- Backfill student_details from profiles + students
INSERT INTO public.student_details (user_id, sbrn, semester, session, registration_date, attendance_rate)
SELECT
    p.id,
    p.student_id,
    p.semester,
    p.session,
    s.registration_date,
    s.attendance_rate
FROM public.profiles p
JOIN public.students s ON p.student_id = s.student_id_text OR p.email = s.email
WHERE p.role = 'student' AND p.student_id IS NOT NULL
ON CONFLICT (user_id) DO NOTHING;

-- Backfill teacher_details from profiles
INSERT INTO public.teacher_details (user_id)
SELECT p.id
FROM public.profiles p
WHERE p.role = 'teacher'
ON CONFLICT (user_id) DO NOTHING;

-- Backfill enrollments from course_instructors
INSERT INTO public.enrollments (user_id, course_id, role_in_course)
SELECT p.id, ci.course_id, 'instructor'
FROM public.course_instructors ci
JOIN public.instructors i ON ci.instructor_id = i.id
JOIN public.profiles p ON p.email = i.email
ON CONFLICT (user_id, course_id) DO NOTHING;

-- Backfill enrollments from attendance (implicit student-course relationship)
INSERT INTO public.enrollments (user_id, course_id, role_in_course)
SELECT DISTINCT p.id, a.course_id, 'student'
FROM public.attendance a
JOIN public.students s ON a.student_id = s.id
JOIN public.profiles p ON (p.student_id = s.student_id_text OR p.email = s.email)
ON CONFLICT (user_id, course_id) DO NOTHING;

-- Backfill user_id in attendance table
UPDATE public.attendance a
SET user_id = p.id
FROM public.students s
JOIN public.profiles p ON (p.student_id = s.student_id_text OR p.email = s.email)
WHERE a.student_id = s.id AND a.user_id IS NULL;


