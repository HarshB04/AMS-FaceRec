-- Attendance Management System Database Schema (PostgreSQL/Supabase compatible)

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id_text TEXT UNIQUE, -- The "STU-001" style ID
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    course TEXT,                -- Added for frontend compatibility
    face_enrolled BOOLEAN DEFAULT FALSE, -- Added for frontend compatibility
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'inactive')), -- Added for frontend compatibility
    attendance_rate FLOAT DEFAULT 0, -- Added for frontend compatibility
    registration_date DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_name TEXT NOT NULL,
    course_code TEXT UNIQUE NOT NULL,
    teacher TEXT,
    schedule TEXT,
    room TEXT,
    student_count INT DEFAULT 0,
    status TEXT DEFAULT 'active'
);

CREATE TABLE attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES students(id),
    course_id BIGINT REFERENCES courses(id),
    date_attended DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT DEFAULT 'absent' CHECK (status IN ('present', 'absent', 'late'))
);

CREATE TABLE instructors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL
);

CREATE TABLE course_instructors (
    course_id BIGINT REFERENCES courses(id),
    instructor_id BIGINT REFERENCES instructors(id),
    PRIMARY KEY (course_id, instructor_id)
);
