-- ── 2.1 Users (unified identity — replaces profiles + students + instructors) ─

CREATE TABLE IF NOT EXISTS public.users (
    id               UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
    role             user_role NOT NULL,
    email            TEXT NOT NULL UNIQUE,
    full_name        TEXT NOT NULL,
    phone            TEXT,
    avatar_url       TEXT,
    branch           TEXT,
    approval_status  TEXT NOT NULL DEFAULT 'approved'
                     CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    is_active        BOOLEAN NOT NULL DEFAULT true,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE  public.users IS 'Single source of truth for every person in the system (admin, teacher, student).';
COMMENT ON COLUMN public.users.approval_status IS 'pending = awaiting admin review, approved = can log in, rejected = access denied.';
COMMENT ON COLUMN public.users.is_active IS 'Soft-delete flag. Inactive users cannot log in.';


-- ── 2.2 Student Details (extension for role = student) ──────────────────────

CREATE TABLE IF NOT EXISTS public.student_details (
    user_id           UUID REFERENCES public.users(id) ON DELETE CASCADE PRIMARY KEY,
    sbrn              TEXT NOT NULL UNIQUE,         -- Student Board Roll Number (e.g. 2024CE001)
    semester          INTEGER NOT NULL CHECK (semester BETWEEN 1 AND 8),
    session           TEXT NOT NULL,                -- Academic session (e.g. 2024 - 2027)
    section           TEXT,
    registration_date DATE DEFAULT CURRENT_DATE,
    attendance_rate   NUMERIC(5,2) DEFAULT 0.00
);

COMMENT ON TABLE public.student_details IS 'Role-specific extension for students. 1:1 with users where role = student.';


-- ── 2.3 Teacher Details (extension for role = teacher) ──────────────────────

CREATE TABLE IF NOT EXISTS public.teacher_details (
