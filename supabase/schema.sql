    ON public.timetable_entries (branch, semester, day_of_week, start_time);
CREATE INDEX IF NOT EXISTS timetable_entries_course_id_idx
    ON public.timetable_entries (course_id);


-- ── 2.7 Enrollments (replaces course_instructors + implicit student-course) ─

CREATE TABLE IF NOT EXISTS public.enrollments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        UUID REFERENCES public.users(id) ON DELETE CASCADE NOT NULL,
    course_id      BIGINT REFERENCES public.courses(id) ON DELETE CASCADE NOT NULL,
    role_in_course TEXT NOT NULL CHECK (role_in_course IN ('student', 'instructor')),
    enrolled_at    TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, course_id)
);

COMMENT ON TABLE public.enrollments IS 'Unified course enrollment for both students and teachers. Replaces old course_instructors table.';


-- ── 2.8 Attendance ──────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.attendance (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- New (preferred) FK
    user_id                UUID REFERENCES public.users(id) ON DELETE CASCADE,
    -- Legacy FK (kept until full migration completes)
    student_id             BIGINT REFERENCES public.students(id),
    course_id              BIGINT REFERENCES public.courses(id),
    timetable_course_code  TEXT,
    timetable_course_name  TEXT,
    department             TEXT,                    -- Legacy
    branch                 TEXT,                    -- Preferred
    semester               TEXT,
    date_attended          DATE NOT NULL DEFAULT CURRENT_DATE,
    time_attended          TIME,
    status                 TEXT DEFAULT 'absent' CHECK (status IN ('present', 'absent', 'late')),
    -- New enrichment columns
    marked_by              UUID REFERENCES public.users(id) ON DELETE SET NULL,
    source                 TEXT DEFAULT 'manual' CHECK (source IN ('face_recognition', 'manual', 'bulk_import')),
    confidence             NUMERIC(5,2),
    marked_at              TIMESTAMPTZ DEFAULT NOW(),
    -- Uniqueness constraints
    UNIQUE (student_id, course_id, date_attended),
    UNIQUE (student_id, timetable_course_code, department, semester, date_attended)
);

COMMENT ON COLUMN public.attendance.marked_by IS 'Teacher or face engine user who marked this record.';
COMMENT ON COLUMN public.attendance.source IS 'How attendance was recorded: face_recognition, manual, or bulk_import.';
COMMENT ON COLUMN public.attendance.confidence IS 'Face recognition confidence score (NULL if manual entry).';


