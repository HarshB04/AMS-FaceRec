    faculty_code   TEXT UNIQUE,
    designation    TEXT,
    specialization TEXT,
    joining_date   DATE
);

COMMENT ON TABLE public.teacher_details IS 'Role-specific extension for teachers. 1:1 with users where role = teacher.';


-- ── 2.4 Admin Details (extension for role = admin) ──────────────────────────

CREATE TABLE IF NOT EXISTS public.admin_details (
