    branch        TEXT,                            -- Preferred over department
    semester      TEXT,
    term          TEXT,
    course_name   TEXT NOT NULL,
    course_code   TEXT NOT NULL,
    teacher       TEXT,
    schedule      TEXT,
    room          TEXT,
    student_count INT DEFAULT 0,
    status        TEXT DEFAULT 'active'
