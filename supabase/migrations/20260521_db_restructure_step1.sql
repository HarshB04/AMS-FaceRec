-- Helper to get role from new users table
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS user_role 
LANGUAGE plpgsql 
STABLE 
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN (SELECT role FROM public.users WHERE id = auth.uid());
END;
$$;

-- Users Table Policies
CREATE POLICY "Users read own" ON public.users FOR SELECT USING (id = auth.uid());
CREATE POLICY "Admins read all" ON public.users FOR SELECT USING (get_my_role() = 'admin');

-- Teachers read students in their courses
CREATE POLICY "Teachers read enrolled students" ON public.users FOR SELECT USING (
  get_my_role() = 'teacher'
  AND id IN (
    SELECT e.user_id FROM public.enrollments e
    WHERE e.course_id IN (
      SELECT e2.course_id FROM public.enrollments e2
      WHERE e2.user_id = auth.uid() AND e2.role_in_course = 'instructor'
    )
  )
);

-- Extension table policies
CREATE POLICY "Read own student details" ON public.student_details FOR SELECT USING (user_id = auth.uid());
CREATE POLICY "Admins read all student details" ON public.student_details FOR SELECT USING (get_my_role() = 'admin');

CREATE POLICY "Read own teacher details" ON public.teacher_details FOR SELECT USING (user_id = auth.uid());
CREATE POLICY "Admins read all teacher details" ON public.teacher_details FOR SELECT USING (get_my_role() = 'admin');

-- Enrollments policies
CREATE POLICY "Read own enrollments" ON public.enrollments FOR SELECT USING (user_id = auth.uid());
CREATE POLICY "Admins read all enrollments" ON public.enrollments FOR SELECT USING (get_my_role() = 'admin');
CREATE POLICY "Teachers read course enrollments" ON public.enrollments FOR SELECT USING (
  get_my_role() = 'teacher' 
  AND course_id IN (
    SELECT course_id FROM public.enrollments WHERE user_id = auth.uid() AND role_in_course = 'instructor'
  )
);
